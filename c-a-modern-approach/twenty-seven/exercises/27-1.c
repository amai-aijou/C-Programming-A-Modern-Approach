int main(void) {

	printf("-------------------EXERCISE 27-1-------------------\n\n");
	printf(COLOR_MAGENTA "Q. Where are the intN_t / uintN_t types in stdint.h located? What values are allowed?\n\n");

	printf(COLOR_CYAN    "    Ans.: " COLOR_RESET "Rocky 9.5 doesn't actually store them in /usr/include/stdin.h.\n"
						 "           Instead, it's in multiple places, including /usr/include/bits/types.h (included in stdint.h)\n"
						 "           Values of 8, 16, 32, and 64 are all allowed, both signed and unsigned. See list below.\n");
	printf(COLOR_CYAN    "  Output: \n" COLOR_RESET); 

	printf("    typedef signed char __int8_t;\n");
	printf("    typedef unsigned char __uint8_t;\n");
	printf("    typedef signed short int __int16_t;\n");
	printf("    typedef unsigned short int __uint16_t;\n");
	printf("    typedef signed int __int32_t;\n");
	printf("    typedef unsigned int __uint32_t;\n");
	printf("    #if __WORDSIZE == 64\n");
	printf("    typedef signed long int __int64_t;\n");
	printf("    typedef unsigned long int __uint64_t;\n");
	printf("    #else\n");
	printf("    __extension__ typedef signed long long int __int64_t;\n");
	printf("    __extension__ typedef unsigned long long int __uint64_t;\n");
	printf("    #endif\n");

	return 0;
}

