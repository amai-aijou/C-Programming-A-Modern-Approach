int main(void) {

	if (setjmp(env) == 0) {
		printf("setjmp returned 0\n");
	} else {
		printf("Program terminates: longjmp called\n");
		return 0;
	}

	f1();
	printf("Program terminates normally\n");
	return 0;

}

