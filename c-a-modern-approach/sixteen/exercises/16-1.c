int main(void) {

	struct { int x, y;} x;
	struct { int x, y;} y;

	printf("Q. Are these declarations legal on an individual basis?\n"
			"Could both Declarations appear as shown in a program?\n\n");

	printf("A. These are both legal, but will not have any meaningful values yet.\n\n");

	printf("Before values assigned to x or y:\n");
	printf("x.x: %d\n\n", x.x);

	x.x = 4;
	x.y = 5;
	y.x = 6;
	y.y = 7;

	printf("After values assigned to x and y in each struct:\n");
	printf("x.x: %d\n", x.x);
	printf("x.y: %d\n", x.y);
	printf("y.x: %d\n", y.x);
	printf("y.y: %d\n", y.y);

	return 0;
}

