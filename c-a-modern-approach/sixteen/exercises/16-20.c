int main(void) {
	int x = 0,y = 0;

	printf("\n-------------------EXERCISE 16-20------------------\n");
	// Print original coordinates
	printf("coordinates: %d,%d\n", x, y);

	// Determine direction
	direction = EAST;

	// Check direction, then perform operation
	switch (direction) {
		case EAST: ++x;
				   break;
		case WEST: --x;
				   break;
		case SOUTH: ++y;
					break;
		case NORTH: --y;
					break;
	}

	// Print new coordinates
	printf("coordinates: %d,%d\n", x, y);

	return 0;
}

