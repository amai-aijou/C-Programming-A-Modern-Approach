#include <stdio.h>

#define RECTANGLE 0
#define SQUARE 1

struct point {
	int x,y;
};

struct shape {
	int shape_kind;
	struct point center;
	union {
		struct {
			int height, width;
		} rectangle;
		struct {
			int radius;
		} circle;
	} u;
} s;

