int main(void) {

	printf("-------------------EXERCISE 22-4-------------------\n\n");
	printf(COLOR_MAGENTA "Q. How will each of these look display as %%#012.5g?\n\n");


	printf(COLOR_MAGENTA "(a)83.7361\n");
	printf(COLOR_CYAN    "  Output: " COLOR_RESET "%#012.5g\n\n", 83.7361 );

	printf(COLOR_MAGENTA "(b) 29748.6607\n");
	printf(COLOR_CYAN    "  Output: " COLOR_RESET "%#012.5g\n\n", 29748.6607);

	printf(COLOR_MAGENTA "(c) 1054932234.0\n");
	printf(COLOR_CYAN    "  Output: " COLOR_RESET "%#012.5g\n\n", 1054932234.0);

	printf(COLOR_MAGENTA "(d) 0.0000235218\n");
	printf(COLOR_CYAN    "  Output: " COLOR_RESET "%#012.5g\n\n", 0.0000235218);

	return 0;
}

