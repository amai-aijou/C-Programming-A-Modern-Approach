int main(void) {

	char charTest[5];
	char stringTest[5];

	printf("-------------------EXERCISE 22-8-------------------\n\n");
	printf(COLOR_MAGENTA "Q. \"%%c\" is sometimes used to skip whitespace. some programmers use %%1s instead. Are they the same?\n\n");

	printf(COLOR_CYAN    "  char: " COLOR_RESET); 
	scanf(                               " %c", &charTest);

	printf(COLOR_CYAN    "string: " COLOR_RESET); 
	scanf(                               "%1s", &stringTest);

	printf(COLOR_CYAN    "       output (char): " COLOR_RESET "%c\n", charTest[0]); 
	printf(COLOR_CYAN    "     output (string): " COLOR_RESET "%s\n", stringTest); 

	printf(COLOR_CYAN    "        Same?: " COLOR_RESET "They are very similar, however %%1s can only be used on a string or char array, as it appends \\0 at the end.\n"
		                 "                This reduces the flexibility. Also, you can use %%c for a string, though neither of these sound like a great idea.\n\n");

	return 0;
}

