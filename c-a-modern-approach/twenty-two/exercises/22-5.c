int main(void) {

	int test = -100;

	printf("-------------------EXERCISE 22-5-------------------\n\n");
	printf(COLOR_MAGENTA "Q. What, if any, is the difference between %%.4d and %%04d?\n\n");

	printf(COLOR_MAGENTA "%%.4d: \n");
	printf(COLOR_CYAN    "  Notes: " COLOR_RESET "Produces a four digit output in all situations\n");
	printf(COLOR_CYAN    " Output: " COLOR_RESET "%.4d\n\n", test); 

	printf(COLOR_MAGENTA "%%04d: \n");
	printf(COLOR_CYAN    "  Notes: " COLOR_RESET "Produces a 4+ digit output for positive numbers; it'll be one short for negative (sign counts in the field width!)\n");
	printf(COLOR_CYAN    " Output: " COLOR_RESET "%04d\n\n", test); 

	return 0;
}

