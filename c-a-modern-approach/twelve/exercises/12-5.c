int main(void) {

	int a[10];
	int *p;

	p = a;

	/* A should be illegal, can't compare pointer to integer
	if (p == a[0]) {
		printf("A is legal and true");
	} */
	printf("A is illegal, cannot compare pointer to integer.\n");

	// B should be legal and true, "p = a" is equivalent to "p = a[0]"
	if (p == &a[0]) {
		printf("B is legal and true\n");
	}

	// C should be legal and true, as *p points to a[0]
	if (*p == a[0]) {
		printf("C is legal and true\n");
	}

	// D should be legal, p[0] is equivalent to "*p + 0", and a[0] is equivalent to "a + 0"
	if (p[0] == a[0]) {
		printf("D is legal and true\n");
	}

	return 0;
}

