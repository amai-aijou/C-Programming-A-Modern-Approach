/*┏━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━┓
                   ❤︎︎࣪    F U N C T I O N S    ❤︎︎࣪    
  ┗━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━┛*/
int find_largest(int a[], int n) {

	int i, max;

	max = a[0];
	for (i = 1; i < n; i++) {
		if (a[i] > max) {
			max = a[i];
		}
	}

	return max;
}

int find_largest_arith(int *a, int n) {

	int *p;
	int max = 0;

	for (p = a + 1; p < a + n; p++) {
		
		if (*p > max) {
			max = *p;
		}
	}

	return max;
}
