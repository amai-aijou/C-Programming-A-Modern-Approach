void read_user_input_arith(char a[], int *n) {

	char *p = a;
	char ch;

	printf("Enter a message: ");
	while ((ch = getchar()) != '\n') {
		if (isalpha(ch)) {
			*(p + (*n)++) = tolower(ch);	
		}
	}
}

bool check_palindrome(char a[], int *n) {

	char *p = a;
	char ch;
	int x = 0;

	for (p = a; p <= a + (*n/2); p++) {

		if (*p != *(p + (*n-1) - x)) {	
			return false;
		}
		x += 2;
	}

	return true;
}

void print_array(char a[], int *n) {

	char *p;

	for (p = a; p < a + *n; p++) {
		printf("%c ", *p);
	}
	printf("\n");
}
