int main(void) {

	char lower = 'x';
	char upper = 'X';

	printf("-------------------EXERCISE 21-5-------------------\n\n");
	printf(COLOR_MAGENTA "Q. What makes this macro illegal?\n"
		   COLOR_RESET   "  Note: This macro is from <ctype.h>\n\n");

	printf(COLOR_CYAN    "  #define islower(c) ((c) >= 'a' && (c) <= 'z')\n");

	printf(COLOR_CYAN    "  Guess: " COLOR_RESET "It's illegal as <ctype.h> defines islower not only as a function, but as a macro:\n\n"
	                     "         #define islower(c) __isctype((c), _ISlower)\n\n"
						 "         As such, you must first #undef it, first, which erases the function. since this *is* just a function though,\n"
						 "          you can use islower as a macro as long as <ctype.h> isn't included. It's not a globally reserved name!\n\n");

	printf(COLOR_CYAN    "Proof:\n");
	printf(              "Lower is lowercase: %d\n", islower(lower));
	printf(              "Upper is uppercase: %d\n\n", islower(upper));

	return 0;
}

