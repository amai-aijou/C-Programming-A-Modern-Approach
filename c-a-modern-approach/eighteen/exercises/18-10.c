int main(void) {

	printf("-------------------EXERCISE 18-10-------------------\n\n");
	printf(COLOR_MAGENTA "Q. Write a declaration for each variable/function:\n\n");

	printf(COLOR_CYAN "(a) p is a pointer to a function whith a character pointer argument that returns a character pointer.\n");
	printf(COLOR_MAGENTA "Declaration: " COLOR_RESET "char *(*p)(char *)\n\n");

	printf(COLOR_CYAN "(b) f is a function with two arguments: p, a pointer to a struct with tag t, and n, a long integer.\n"
			          "    f returns a pointer to a function that has no arguments and returns nothing.\n");
	printf(COLOR_MAGENTA "Declaration: " COLOR_RESET "void (*f(struct t *p, long int n))(void)\n\n");

	printf(COLOR_CYAN "(c) a is an array of four pointers to functions that have no arguments and return nothing.\n"
			          "    The elements of a initially point to functions named insert, search, update, and print.\n");
	printf(COLOR_MAGENTA "Declaration: " COLOR_RESET "void (*a[4])(void) = {insert,\n"
			             "                                                  search,\n"
						 "                                                  update,\n"
						 "                                                  print};\n\n");

	printf(COLOR_CYAN "(d) b is an array with 10 pointers to functions with two int arguments that return structures with tag t.\n");
	printf(COLOR_MAGENTA "Declaration: " COLOR_RESET "struct t (*b[10])(int, int)\n\n");

	return 0;
}

