// appends the extension of the filename into the string
void get_extension(const char *file_name, char *extension) {

	int i;

	if (strlen(file_name) == 0) {
		printf("String has zero length.\n");
		extension[0] = '\0';
	}

	for (i = 0; ; i++) {
		if (file_name[i] == '.') {
			break;
		}
	}

	strcpy(extension, &file_name[i+1]);

}

void zero_array(char str[], int n) {

	int i;

	for (i = 0; i < n; i++) {
		str[i] = 0;
	}
}

void print_array(const char str[], int n) {

	int i;

	for (i = 0; i < n; i++) {
		printf("%c",str[i]);
	}
	printf("\n");
}
