// Capitalizes all letters in its argument
int capitalize(char str[], int n) {

	int i;

	for (i = 0; i < n; i++) {
		str[i] = toupper(str[i]);
	}

	return i;
}

// Capiralizes all letters, using pointer arithmetic
int capitalize_arith(char str[], int n) {

	char *p;
	int i;

	for (p = str; p < p + n; p++) {
		*p = toupper(*p);
		i++;
	}

	return i;
}

void print_array(char str[], int n) {
	
	int i;

	for (i = 0; i < n; i++) {
		printf("%c", str[i]);
	}
	printf("\n");
}
