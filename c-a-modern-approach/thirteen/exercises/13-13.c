void build_index_url(const char *domain, char *index_url) {

	const char prefix[] = "http://www.";
	char index[] = "/index.html";

	//copy prefix to final index_url
	strcpy(index_url,prefix);

	//add domain to end of index_url
	strcat(index_url,domain);

	//add index suffix to index_url
	strcat(index_url,index);
}

void print_array(const char str[], int n) {

	int i;

	for (i = 0; i < n; i++) {
		printf("%c",str[i]);
	}
	printf("\n");
}
