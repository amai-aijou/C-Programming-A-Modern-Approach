int square_root_close_enough(int x) {

	int i = 0;
	
	while (i * i <= x) {

		if ((i + 1) * (i + 1) <= x) {

			i++;
			// to bring i up to a decent whole number
		} else {

			break;
		}
	}

	return i;
}

int product(int x, int y) {

	return x * y;
}
