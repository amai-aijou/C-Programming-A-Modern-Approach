/*┏━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━┓
                ❤︎︎    M A I N  F U N C T I O N    ❤︎︎                
  ┗━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━┛*/
int main(void) {

	char s[50];
	int i = 0;

	printf("\n");
	printf("(a) strcpy(s, \"abcd\"); i = 0; putchar(TOUPPER(s[++i]));\n");
	printf("  Output: ");
	strcpy(s, "abcd");
	i = 0;
	putchar(TOUPPER(s[++i]));
	printf("\n  Answer: The macro has four calls to (c), so ++i happens 4x!\n\n");


	printf("(b) strcpy(s, \"0123\"); i = 0; putchar(TOUPPER(s[++i]));\n");
	printf("  Output: ");
	strcpy(s, "0123");
	i = 0;
	putchar(TOUPPER(s[++i]));
	printf("\n  Answer: It only uses the 'else' portion of the 'if:then?else' statement, so it happens twice.\n\n");

	printf("The big takeaway is that ++i/i++ seems to trigger once for each 'pass' of the pre-processor...\n");
	printf("  ...and once more for the actual codebase, so it will generally trigger twice at *minimum*!\n");
	printf("\n");

	return 0;
}

