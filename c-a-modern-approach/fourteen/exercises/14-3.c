	printf("  A: %d\n", DOUBLE(1+2));
	printf("  A (fixed): %d\n", DOUBLEFIX(1+2));

	printf("(b) What is the value of 4/DOUBLE(2)?\n");
	printf("  A: %d\n", 4/DOUBLE(2));
