// 3. This intermediary forces __LINE__ to evaluate before being stringized!
// 2. Calls STR(Line 32 of file)
#define STR2(x) STR(x)

// 1. Calls STR2(Line __LINE__ of file)
#define LINE_FILE STR2(Line __LINE__ of file)

