/*┏━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━┓
                ❤︎︎    M A I N  F U N C T I O N    ❤︎︎                
  ┗━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━┛*/
int main(void) {

	GENERIC_MAX(long);

	printf("(a) The preprocessor expansion (as evidenced by gcc -E) is:\n");
	printf("long long_max(long x, long y) { return x > y ? x : y; };\n");

	GENERIC_MAX(unsigned long);

	printf("(b) Preprocessor expansion tries to name the function 'unsigned long_max', which is illegal:\n");
 	printf("unsigned long unsigned long_max(unsigned long x, unsigned long y) { return x > y ? x : y; };\n");

	GENERIC_MAX(ulong);

	printf("(c) Adding 'typedef unsigned long ulong' to the top of the program results in 'ulong_max', a perfectly legal name:\n");
 	printf("ulong ulong_max(ulong x, ulong y) { return x > y ? x : y; };\n");


	return 0;
}

