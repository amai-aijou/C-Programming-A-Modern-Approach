void *my_malloc(size_t n) {

	void *p;

	p = malloc(n);
	if (p == NULL) {
		printf("ERROR: Null Pointer created. My fault, your responsibility!\n");
		exit(EXIT_FAILURE);
	}

	return p;
}

int *create_array(int n, int initial_value) {

	int i;
	int *new_array = my_malloc(n * sizeof(int));

	for (i = 0; i < n; i++) {
		new_array[i] = initial_value;
	}
}
