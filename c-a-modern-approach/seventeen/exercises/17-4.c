int main(void) {

	struct rectangle *p;

	p = malloc(sizeof(struct rectangle));

	p->upper_left.x = 10;
	p->upper_left.y = 25;
	p->lower_right.x = 20;
	p->lower_right.y = 15;

	printf("p->lower_right.y (should be 15): %d\n", p->lower_right.y);

	return 0;
}

