int main(void) {

	unsigned int n = 15;



	printf("-------------------EXERCISE 20-13-------------------\n\n");
	printf(COLOR_MAGENTA "Q. What does this statement do? (hint: it may run more than once!)\n\n");

	printf(COLOR_CYAN    "    unsigned int n;\n"
			             "    n &= n - 1;\n\n");

	printf(COLOR_CYAN    "  Guess: " COLOR_RESET "n causes the right-most 1 bit to flip to a zero, ie:\n"
			             "           15: 1111...1110...1100...1000\n\n");
	printf(COLOR_CYAN    " Output: \n" COLOR_RESET); 

	printf(              "        n: %d\n", n);
	n &= n - 1;
	printf(              "   Run 1x: %d\n", n);
	n &= n - 1;
	printf(              "   Run 2x: %d\n", n);
	n &= n - 1;
	printf(              "   Run 2x: %d\n", n);

	return 0;
}

