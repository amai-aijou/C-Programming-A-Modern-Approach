void input_output(void) {

	int count = 0;
	int ch;

	while ((ch = fgetc(stdin)) != EOF) {

		while (ch == '.' || ch == '?' || ch == '!') {
			if (((ch = fgetc(stdin)) != EOF) && (isspace(ch))) {
				count++;
			}
		}
	}

	printf("Total sentence count: %d\n", count);
	printf("Note: a sentence is any occurence of[.?!] followed by newline char\n\n");

}
