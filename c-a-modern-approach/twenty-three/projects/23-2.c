void input_output(void) {

		bool newline = true;
		int ch;

		while ((ch = fgetc(stdin)) != EOF) {

			while ((ch == ' ') && (newline == true)) {
				ch = fgetc(stdin);
			}

			if (ch == '\n' && newline == false) {
				newline = true;
				fputc(ch,stdout);
			} else if (ch == '\n' && newline == true) {
				continue;
			} else {
				fputc(ch,stdout);
				newline = false;
			}
		}
}
