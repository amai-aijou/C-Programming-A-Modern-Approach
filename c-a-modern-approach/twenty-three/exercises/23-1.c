// Rounds to nearested Decimal
double round_nearest(double x) {
	return x < 0.0 ? ceil(x - 0.5) : floor(x + 0.5);
}

// Rounds to nearest decimal n digits to the right of the decimal point.
double round_nearest_decimal(double x, double n) {

	// Multiply x by 10^n to move n digits left of the decimal point 
	x *= pow(10, n);

	// After multiplication, anything left of the decimal point is protected
	x = round_nearest(x);

	// Divide x by 10^n to restore the n digits to the right of the decimal point
	x /= pow(10, n);

	return x;
}
