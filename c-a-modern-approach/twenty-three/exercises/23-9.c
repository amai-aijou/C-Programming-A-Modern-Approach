int main(void) {

	char ch = 'a';

	printf("-------------------EXERCISE 23-9-------------------\n\n");
	printf(COLOR_MAGENTA "Q. Recreate this if statement using only one call of strchr()!\n\n");

	printf(COLOR_CYAN    "    if (ch == 'a' || ch == 'b' || ch == 'c')\n\n");

	printf(COLOR_MAGENTA "  (1) Original Statement\n");
	printf(COLOR_RESET   "    if (ch == 'a' || ch == 'b' || ch == 'c')\n");
	printf(COLOR_CYAN    "   Output: " COLOR_RESET); 

	if (ch == 'a' || ch == 'b' || ch == 'c') {
		printf("True\n");
	} else {
		printf("False\n");
	}

	printf(COLOR_MAGENTA "  (2) strchr() Statement\n");
	printf(COLOR_RESET   "    if (strchr(\"abc\", ch))\n");
	printf(COLOR_CYAN    "   Output: " COLOR_RESET); 

	if (strchr("abc", ch)) {
		printf("True\n");
	} else {
		printf("False\n");
	}
	printf(COLOR_CYAN    "     Exp.: " COLOR_RESET "Build a string with all valid chars...\n"
		                 "           ...then use the char to search the string. Uno reverse!\n\n"); 

	return 0;
}

