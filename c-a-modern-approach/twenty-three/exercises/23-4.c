bool legality_checker_c(char *identifier) {

	bool legal = true;
	char *p = identifier;
	int i = 0;

	for (p = 0; p < (p + i); p++) {

		if ((!isalnum(identifier[i])) && (identifier[1] != '_')) {
			legal = false;
		}
		i++;
	}

	if ((!isalpha(identifier[0])) && (identifier[0] != '_')) {
		legal = false;
	}

	return legal;
}
