int main(void) {

	char *str = "baz";

	printf("-------------------EXERCISE 23-10-------------------\n\n");
	printf(COLOR_MAGENTA "Q. Recreate this if statement using only one call of strstr()!\n\n");

	printf(COLOR_MAGENTA "  (1) Original Statement\n");
	printf(COLOR_RESET    "    if (strcmp(str, \"foo\") == 0 || strcmp(str, \"bar\") == 0 ||\n"
			             "     strcmp(str, \"baz\") == 0));\n");
	printf(COLOR_CYAN    "     Output: " COLOR_RESET); 
	if (strcmp(str, "foo") == 0 || strcmp(str, "bar") == 0 ||  strcmp(str, "baz") == 0) {
		printf("String is equal to foo, bar, or baz\n\n");
	} else {
		printf("Not found!\n\n");
	}

	printf(COLOR_MAGENTA "  (2) Amended Statement\n");
	printf(COLOR_CYAN    "     Output: " COLOR_RESET); 
	if (strstr("foo,bar,baz", str )) {
		printf("String is equal to foo, bar, or baz\n\n");
	} else {
		printf("Not found!\n\n");
	}
	printf(COLOR_CYAN    "       Exp.: " COLOR_RESET "This will match a substring, as well as the actual string!\n\n"); 

	return 0;
}

