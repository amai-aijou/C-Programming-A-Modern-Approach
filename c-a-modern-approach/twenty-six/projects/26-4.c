/*┏━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━┓
                  ❤︎︎࣪    P R O T O T Y P E S    ❤︎︎࣪    
  ┗━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━┛*/
struct tm build_time(int mon, int mday, int year);
void print_time(struct tm *time, char *format);

/*┏━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━┓
                ❤︎︎    M A I N  F U N C T I O N    ❤︎︎                
  ┗━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━┛*/
int main(void) {

	int mon, mday, year, n;
	struct tm time;

	printf("Please enter a date (MM-DD-YYYY): ");
	scanf("%2d-%2d-%d", &mon, &mday, &year);

	printf("Enter number of days to fast-forward: ");
	scanf("%d", &n);

	time = build_time(mon, (mday + n), year);

	print_time(&time, "%A, %b %d, %Y (%D)");

	return 0;
}

/*┏━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━┓
                   ❤︎︎࣪    F U N C T I O N S    ❤︎︎࣪    
  ┗━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━┛*/
struct tm build_time(int mon, int mday, int year)  {

	struct tm t;

	t.tm_mday = mday;
	t.tm_mon = (mon - 1);
	t.tm_year = year;
	t.tm_sec = 0;
	t.tm_min = 0;
	t.tm_hour = 0;
	t.tm_isdst = -1;

	mktime(&t);

	return t;
}

void print_time(struct tm *time, char *format) {

	char time_string[100];

	strftime(time_string, sizeof(time_string), format, time);

	printf("The new time is:\n\n%s\n\n", time_string);
}
