int main(void) {

	char str[MAX_STR];
	time_t cur_time = time(NULL);
	struct tm *t = localtime(&cur_time);

	printf("-------------------EXERCISE 26-13-------------------\n\n");
	printf(COLOR_MAGENTA "Q. Apply the following strtime() formats to the current time\n\n");

	printf(COLOR_CYAN    "    %s\n", ctime(&cur_time)); 

	printf(COLOR_MAGENTA "(a) YYY-DDD (d = 1-366)\n");
	strftime(str, MAX_STR, "%Y-%j", t);
	printf(COLOR_CYAN    "    Output: " COLOR_RESET "%s\n\n", str); 

	printf(COLOR_MAGENTA "(b) YYYY-Www-D (W = divider, ww = 1-53, D = 1-7)\n");
	strftime(str, MAX_STR, "%Y-W%V-%u", t);
	printf(COLOR_CYAN    "    Output: " COLOR_RESET "%s\n\n", str); 

	printf(COLOR_MAGENTA "(c) YYYY-MM-DDThh:mm:ss (T = divider)\n");
	strftime(str, MAX_STR, "%FT%H:%M:%S", t);
	printf(COLOR_CYAN    "    Output: " COLOR_RESET "%s\n\n", str); 

	return 0;
}

