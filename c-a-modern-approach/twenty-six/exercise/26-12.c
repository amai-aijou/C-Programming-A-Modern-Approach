time_t year_to_ctime(int year) {

	struct tm t = {0};

	t.tm_sec = 0;
	t.tm_min = 0;
	t.tm_hour = 0;
	t.tm_mday = 0;
	t.tm_mon = 0;
	t.tm_year = year - 1900;

	return mktime(&t);
}

int ctime_to_year(time_t cYear){

	return (cYear / (60 * 60 * 24 * 365)) + 1970;
}
