char main(void) {
	
	char ch;
	int maxStack = 0;
	Stack s1;

	s1 = create();

	printf("Enter parentheses and/or braces: ");



	while ((ch = getchar()) != '\n') {

		if (ch == '{' || ch == '(') {
			push(s1,ch);	
		}

		if (ch == '}' || ch == ')') {
			pop(s1);	
		}

		maxStack++;
	}

	print_leftovers(s1,maxStack);

	if (is_empty(s1)) {
		printf("Parentheses/braces are nested properly.\n");
		//printf("Empty!\n");
	} else stack_underflow();

	return 0;
}
