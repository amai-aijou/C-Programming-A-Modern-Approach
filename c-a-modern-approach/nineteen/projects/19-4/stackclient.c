/*┏━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━┓
                ❤︎︎    M A I N  F U N C T I O N    ❤︎︎                
  ┗━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━┛*/
int main(void) {

	Stack s1, s2;
	int *n;

	s1 = create();
	s2 = create();

	// Must manage memory yourself in a type-agnostic program
	int *p1 = malloc(sizeof(int));
	int *p2 = malloc(sizeof(int));

	*p1 = 1;
	*p2 = 2;

	push(s1, p1);
	push(s1, p2);

	n = pop(s1);
	printf("Popped %d from s1\n", *n);
	push(s2, p2);
	n = pop(s1);
	printf("Popped %d from s1\n", *n);
	push(s2, p2);

	destroy(s1);

	while (!is_empty(s2)) {
		// returns type "void *", so it needs to be cast to "int *", then dereferenced
		// (so it shows the value, instead of the address!)
		printf("Popped %d from s2\n", *(int *)pop(s2));
	}

	*p2 = 3;
	push(s2, p2);
	make_empty(s2);
	if (is_empty(s2)) {
		printf("s2 is empty!\n");
	} else {
		printf("s2 is not empty\n");
	}

	destroy(s2);

	return 0;
}

