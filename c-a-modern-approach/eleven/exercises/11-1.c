int main(void) {

	int i = 1;
	int *p;

	p = &i;

	printf("p:%d | i:%d\n", p, i);
	printf("&p:%d | &i:%d\n", &p, &i);
	printf("*p:%d \n", *p);
	printf("*&p:%d | &*p:%d\n", *&p, &*p);
	printf("*&i:%d \n", *&i);

	return 0;
}

